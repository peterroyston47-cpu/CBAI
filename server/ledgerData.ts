export function buildOrderBook(asset: AiAsset): OrderBookSnapshot {
  const protocols = asset.supportedProtocols;
  const mid = asset.priceUsd;
  const step = Math.max(mid * 0.0018, 0.001);

  const bids = Array.from({ length: 8 }, (_, idx) => {
    const level = idx + 1;
    const price = Number((mid - step * level).toFixed(mid >= 100 ? 2 : 4));
    const size = Number(((120 + idx * 55) * (10 / Math.max(mid, 1))).toFixed(2));
    return {
      price,
      size: Math.max(size, 1.5),
      total: Number((price * Math.max(size, 1.5)).toFixed(2)),
      protocol: protocols[idx % protocols.length] as ProtocolId,
    };
  });

  const asks = Array.from({ length: 8 }, (_, idx) => {
    const level = idx + 1;
    const price = Number((mid + step * level).toFixed(mid >= 100 ? 2 : 4));
    const size = Number(((110 + idx * 52) * (10 / Math.max(mid, 1))).toFixed(2));
    return {
      price,
      size: Math.max(size, 1.5),
      total: Number((price * Math.max(size, 1.5)).toFixed(2)),
      protocol: protocols[(idx + 1) % protocols.length] as ProtocolId,
    };
  });

  return {
    assetId: asset.id,
    midPrice: mid,
    spreadBps: 18,
    bids,
    asks,
  };
}
